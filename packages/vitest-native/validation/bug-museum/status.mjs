// Records measured verdicts into exhibits.json (`status`) and renders STATUS.md.
//
//   node validation/bug-museum/status.mjs --commit <sha of the main build>
//        --main <run.mjs --json of main> [--fix <json>] [--buggy <json>]
//        [--pre-fix <json>] [--control <json>]
//
// Each JSON is what run.mjs --json wrote for one column: main (origin/main), fix (each
// exhibit against the build of its `fixRef`), buggy (its `buggyRef`: the build that
// introduced a regression the exhibit guards against), pre-fix (its `preFixRef`: the
// build before an already-landed fix) and control (run.mjs --control on main).
//
// An exhibit is LOAD-BEARING when a build with the bug fails it and a build without the
// bug passes it:
//   fix proven     main FAIL (the bug), fixRef PASS
//   guard proven   main PASS, buggyRef FAIL (the bug)   (a regression of a fix PR)
//   landed proven  preFixRef FAIL (the bug), main PASS  (a fix already on main)
//   open           main FAIL (the bug), control PASS    (no fix yet; the control shows
//                  the exhibit can pass once the bug's precondition is gone)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const argument = (name) => {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? undefined : process.argv[index + 1];
};
const read = (name) =>
  argument(name) ? JSON.parse(fs.readFileSync(argument(name), "utf8")).verdicts : {};

const columns = {
  main: read("main"),
  fix: read("fix"),
  buggy: read("buggy"),
  preFix: read("pre-fix"),
  control: read("control"),
};
const commit = argument("commit");
if (!commit) throw new Error("--commit <sha> is required");

/** "PASS" | "FAIL (bug)" | "FAIL (other)" | "N/A" | undefined */
function cell(verdict) {
  if (!verdict) return undefined;
  if (verdict.verdict === "FAIL")
    return verdict.matchesBug === false ? "FAIL (other)" : "FAIL (bug)";
  return verdict.verdict;
}

// Absolute paths in failure lines are machine-specific: keep the message, not the path.
const scrub = (line) =>
  line
    .replace(
      /\/(?:private\/)?(?:tmp|var)\/[^\s'"]*\/(?:work|vn-bug-museum-[^/\s]+)\/[^/\s]+\//g,
      "<exhibit>/",
    )
    .replace(/\/Users\/[^/\s]+\//g, "~/")
    .slice(0, 240);

function proof(exhibit, status) {
  if (status.main === "FAIL (bug)" && status.fix === "PASS") return "fix proven";
  if (status.main === "PASS" && status.buggy === "FAIL (bug)") return "guard proven";
  if (status.main === "PASS" && status.preFix === "FAIL (bug)") return "landed proven";
  if (status.main === "FAIL (bug)" && status.control === "PASS")
    return exhibit.fixVerification ? "open: fix side requires-CI" : "open (control passes)";
  if (status.main === "FAIL (bug)" && exhibit.fixVerification) return "fix side requires-CI";
  if (status.main === "N/A") return "requires-CI";
  return "NOT PROVEN";
}

const manifestFile = path.join(here, "exhibits.json");
const manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));
for (const exhibit of manifest.exhibits) {
  const status = { measuredOn: commit };
  for (const [name, verdicts] of Object.entries(columns)) {
    const value = cell(verdicts[exhibit.id]);
    if (value) status[name] = value;
  }
  const main = columns.main[exhibit.id];
  if (main?.verdict === "FAIL") status.mainSignature = scrub(main.failures[0]);
  if (main?.verdict === "N/A") status.mainReason = main.reason;
  status.proof = proof(exhibit, status);
  exhibit.status = status;
}
fs.writeFileSync(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`);

// --- STATUS.md --------------------------------------------------------------------
const CLASSES = [
  "ownership",
  "env-contract",
  "per-file-state",
  "presets",
  "transform/resolution",
  "harness",
  "config",
];
const rows = manifest.exhibits;
const count = (pred) => rows.filter(pred).length;
const withFix = (e) => {
  const s = e.status;
  const parts = [];
  if (s.buggy) parts.push(`guard: ${s.buggy} on ${e.buggyRef.replace(/^origin\//, "")}`);
  if (s.fix) parts.push(`${s.fix} (${e.fixRef.replace(/^origin\//, "")})`);
  if (s.preFix) parts.push(`landed: ${s.preFix} before (${e.preFixRef})`);
  return parts.join("; ") || "-";
};
const lines = [
  "# Bug museum status",
  "",
  `Measured on origin/main \`${commit}\` (Node ${process.version.slice(1)}, Vitest 5.0.5 unless the exhibit needs 4.1.11, RNTL 14.1 unless it needs 12/13). Generated by \`status.mjs\` from \`run.mjs --json\` output; see README.md for how to reproduce each column.`,
  "",
  `- **${rows.length} exhibits.** ${count((e) => e.status.main?.startsWith("FAIL"))} fail on main today; ${count((e) => e.status.main === "PASS")} pass on main (${count((e) => e.status.proof === "guard proven")} regression guards for open fix PRs, ${count((e) => e.status.proof === "landed proven")} landed fix).`,
  `- **Load-bearing:** ${count((e) => ["fix proven", "guard proven", "landed proven"].includes(e.status.proof))} proven against a build without the bug (fix, guard or landed); ${count((e) => e.status.proof.startsWith("open"))} open bugs fail on main and pass their control; ${count((e) => e.status.proof === "NOT PROVEN")} not proven.`,
  "",
  "Columns: **main** is origin/main. **With fix** is the exhibit against the build of its fix branch (`fixRef`), or for a regression guard the build that regresses (`buggyRef`), or for a landed fix the build before it (`preFixRef`). **Control** is `run.mjs --control` on main: the exhibit with the bug's precondition removed, which must pass. `FAIL (bug)` matches the exhibit's recorded `bugSignature`; `FAIL (other)` does not.",
  "",
  "| Exhibit | Class | Fixed by | main | With fix | Control | Proof |",
  "|---|---|---|---|---|---|---|",
  ...CLASSES.flatMap((cls) =>
    rows
      .filter((e) => e.class === cls)
      .map(
        (e) =>
          `| [${e.id}](exhibits/${e.id}/README.md) | ${e.class} | ${e.fixedBy} | ${e.status.main ?? "-"} | ${withFix(e)} | ${e.status.control ?? "-"} | ${e.status.proof} |`,
      ),
  ),
  "",
  "## By class",
  "",
  "| Class | Exhibits | Fail on main | Open (no fix that passes) |",
  "|---|---|---|---|",
  ...CLASSES.map((cls) => {
    const of = rows.filter((e) => e.class === cls);
    return `| ${cls} | ${of.length} | ${of.filter((e) => e.status.main?.startsWith("FAIL")).length} | ${of.filter((e) => e.status.proof.startsWith("open")).length} |`;
  }),
  "",
  "## Failure on main, per exhibit",
  "",
  ...rows
    .filter((e) => e.status.mainSignature)
    .map((e) => `- \`${e.id}\`: ${e.status.mainSignature.replaceAll("|", "\\|")}`),
  "",
];
const notes = rows.filter((e) => e.fixVerification);
if (notes.length > 0) {
  lines.push("## Not verifiable locally", "");
  for (const e of notes) lines.push(`- \`${e.id}\`: ${e.fixVerification}`);
  lines.push("");
}
fs.writeFileSync(path.join(here, "STATUS.md"), lines.join("\n"));
console.log(`wrote STATUS.md and the status of ${rows.length} exhibits`);
